#!/usr/bin/env bash
# Local integration workspace: clones the five Bumpist repos side by side and
# links their packages with one pnpm workspace, so a change in one repo can be
# tried in another before anything is published.
#
#   curl -fsSL https://raw.githubusercontent.com/parksubeom/bumpist-ship/main/scripts/dev-workspace.sh | bash
#   # or: bash dev-workspace.sh ~/code/bumpist
set -euo pipefail

DIR="${1:-$PWD/bumpist-workspace}"
OWNER="parksubeom"
REPOS=(bumpist-design bumpist-agents bumpist-code bumpist-ship claude-distill)

mkdir -p "$DIR" && cd "$DIR"
for r in "${REPOS[@]}"; do
  if [ -d "$r/.git" ]; then
    echo "• $r (exists, pulling)"; git -C "$r" pull --ff-only --quiet || true
  else
    echo "• $r (cloning)"; git clone --quiet "https://github.com/$OWNER/$r.git"
  fi
done

cat > pnpm-workspace.yaml <<'EOF'
# Generated by bumpist-ship/scripts/dev-workspace.sh — do not commit.
packages:
  - bumpist-design/packages/*
  - bumpist-design/apps/*
  - bumpist-code
  - bumpist-code/packages/*
  - claude-distill
EOF
cat > .npmrc <<'EOF'
link-workspace-packages=true
EOF
cat > package.json <<'EOF'
{ "name": "bumpist-workspace", "private": true }
EOF

echo
echo "Workspace ready at $DIR"
echo "Run: cd $DIR && pnpm install   # links @bumpist/* packages across repos"
